const SUPPORTED = Object.keys(TRANSLATIONS);
let currentLang = 'en';

export function initI18n() {
  const stored = localStorage.getItem('cyberpunk-lang');
  if (stored && SUPPORTED.includes(stored)) currentLang = stored;
}

export function setLanguage(lang) {
  if (!SUPPORTED.includes(lang)) return;
  currentLang = lang;
  localStorage.setItem('cyberpunk-lang', lang);
}

export function getLang() { return currentLang; }

export function t(key) {
  return TRANSLATIONS[currentLang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function applyI18n() {
  // Static text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  // Placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });

  // Glitch heading — must update both textContent and data-text
  const glitch = document.querySelector('.glitch');
  if (glitch) {
    const txt = t('title');
    glitch.textContent = txt;
    glitch.dataset.text = txt;
  }

  // Sort <option> elements by value
  const sortMap = {
    default: 'sort_default',
    'title-az': 'sort_title_az',
    'title-za': 'sort_title_za',
    rating: 'sort_rating',
    pages: 'sort_pages',
    added: 'sort_added',
  };
  document.querySelectorAll('#sort-select option').forEach(opt => {
    const key = sortMap[opt.value];
    if (key) opt.textContent = t(key);
  });

  // Active lang button highlight
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}
